package coexistence

import (
	"fmt"

	"sigs.k8s.io/yaml"
)

const (
	// servedVersion is the only AKSNodeClass version served in coexistence mode.
	servedVersion = "v1beta1"
	crdHeader     = "# Code generated by hack/code/coexistence_crd_gen from karpenter.azure.com_aksnodeclasses.yaml. DO NOT EDIT.\n"
)

// helmResourcePolicy asks Helm to keep a resource when its release is uninstalled or no longer
// renders it.
const helmResourcePolicy = "helm.sh/resource-policy"

// keepOnUninstall annotates the metadata of a CRD so that Helm keeps the CRD.
func keepOnUninstall(metadata map[string]any) {
	annotations, _ := metadata["annotations"].(map[string]any)
	if annotations == nil {
		annotations = map[string]any{}
	}
	annotations[helmResourcePolicy] = "keep"
	metadata["annotations"] = annotations
}

// DeriveCRD returns the coexistence AKSNodeClass CRD for the default AKSNodeClass CRD. The
// v1beta1 schema is copied unchanged. Only the name, group, short names, categories and
// unserved versions differ, so that kubectl names stay unambiguous beside the default CRD, and
// the CRD asks Helm to keep it, so that uninstalling its chart never deletes it and with it
// every coexistence AKSNodeClass.
func DeriveCRD(defaultCRD []byte) ([]byte, error) {
	var crd map[string]any
	if err := yaml.Unmarshal(defaultCRD, &crd); err != nil {
		return nil, fmt.Errorf("decoding the AKSNodeClass CRD: %w", err)
	}
	metadata, okMetadata := crd["metadata"].(map[string]any)
	spec, okSpec := crd["spec"].(map[string]any)
	if !okMetadata || !okSpec {
		return nil, fmt.Errorf("the AKSNodeClass CRD needs metadata and spec")
	}
	names, okNames := spec["names"].(map[string]any)
	versions, okVersions := spec["versions"].([]any)
	if !okNames || !okVersions {
		return nil, fmt.Errorf("the AKSNodeClass CRD needs names and versions")
	}
	served := []any{}
	for _, version := range versions {
		if v, ok := version.(map[string]any); ok && v["name"] == servedVersion {
			served = append(served, v)
		}
	}
	if len(served) != 1 {
		return nil, fmt.Errorf("the AKSNodeClass CRD must define version %s exactly once", servedVersion)
	}
	metadata["name"] = CRDName
	keepOnUninstall(metadata)
	spec["group"] = Group
	spec["versions"] = served
	delete(names, "shortNames")
	names["categories"] = []any{"karpenter"}
	out, err := yaml.Marshal(crd)
	if err != nil {
		return nil, fmt.Errorf("encoding the coexistence AKSNodeClass CRD: %w", err)
	}
	return append([]byte(crdHeader), out...), nil
}
